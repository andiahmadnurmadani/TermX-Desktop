const dicts: Record<string, Record<Key, string>> = { en, id };

export function translate(lang: string, key: Key, vars?: Record<string, string | number>): string {
  let s = (dicts[lang] ?? en)[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function useT() {
  const lang = useStore((s) => s.vault?.settings.language ?? "en");
  return (key: Key, vars?: Record<string, string | number>) => translate(lang, key, vars);
}
