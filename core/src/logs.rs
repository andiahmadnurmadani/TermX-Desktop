//! Session history ("Logs"): one [`SessionLog`] row per terminal session, plus an optional raw
//! transcript of everything the server sent, kept as `logs/<id>.log` next to the database.
use crate::model::{now_ms, Host, LogEvent, SessionLog};
use crate::ssh::SessionSink;
use crate::store::Store;
use std::fs::File;
use std::io::{BufWriter, Write};
use std::path::{Path, PathBuf};
use std::sync::{Arc, Mutex};
use std::time::{Duration, Instant};

/// Connection steps kept per log.
const MAX_EVENTS: usize = 200;

/// Transcripts stop growing past this size (the session itself keeps running).
pub const MAX_TRANSCRIPT: u64 = 20 * 1024 * 1024;

pub fn dir(store: &Store) -> PathBuf {
    store.dir().join("logs")
}

pub fn transcript_path(store: &Store, id: &str) -> Option<PathBuf> {
    // ids are generated by the UI; never let one escape the logs directory
    if id.is_empty() || !id.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_') {
        return None;
    }
    Some(dir(store).join(format!("{id}.log")))
}

pub fn remove_transcripts(store: &Store, ids: &[String]) {
    for id in ids {
        if let Some(p) = transcript_path(store, id) {
            let _ = std::fs::remove_file(p);
        }
    }
}

struct Rec {
    log: SessionLog,
    file: Option<BufWriter<File>>,
    written: u64,
    flushed: Instant,
}

/// Wraps the UI sink: forwards everything and records state changes and output.
pub struct LoggingSink {
    inner: Arc<dyn SessionSink>,
    store: Arc<Store>,
    rec: Mutex<Rec>,
}

impl LoggingSink {
    pub fn new(inner: Arc<dyn SessionSink>, store: Arc<Store>, session_id: &str, host: &Host, transcript: bool) -> Arc<Self> {
        let log = SessionLog {
            // a tab can be reopened under the same session id; keep each run separate
            id: format!("{}-{}", sanitize(session_id), now_ms()),
            host_id: host.id.clone(),
            host_label: host.label.clone(),
            username: host.username.clone(),
            hostname: host.hostname.clone(),
            port: host.port,
            started_at: now_ms(),
            status: "connecting".into(),
            ..Default::default()
        };
        let file = if transcript { open_transcript(&store, &log.id) } else { None };
        let mut log = log;
        log.transcript = file.is_some();
        let _ = store.log_upsert(&log);
        if let Ok(old) = store.logs_trim() {
            remove_transcripts(&store, &old);
        }
        Arc::new(LoggingSink { inner, store, rec: Mutex::new(Rec { log, file, written: 0, flushed: Instant::now() }) })
    }
}

fn sanitize(s: &str) -> String {
    let s: String = s.chars().filter(|c| c.is_ascii_alphanumeric() || *c == '-' || *c == '_').take(48).collect();
    if s.is_empty() { "s".into() } else { s }
}

fn open_transcript(store: &Store, id: &str) -> Option<BufWriter<File>> {
    let path = transcript_path(store, id)?;
    std::fs::create_dir_all(path.parent()?).ok()?;
    let f = File::create(&path).ok()?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o600));
    }
    Some(BufWriter::with_capacity(64 * 1024, f))
}

impl SessionSink for LoggingSink {
    fn output(&self, bytes: Vec<u8>) {
        {
            let mut r = self.rec.lock().unwrap();
            r.log.bytes += bytes.len() as u64;
            if r.written < MAX_TRANSCRIPT {
                let n = bytes.len().min((MAX_TRANSCRIPT - r.written) as usize);
                let ok = r.file.as_mut().map(|f| f.write_all(&bytes[..n]).is_ok());
                if ok == Some(false) {
                    r.file = None;
                }
                r.written += n as u64;
            }
            // keep the file readable while the session is still open
            if r.flushed.elapsed() > Duration::from_secs(2) {
                if let Some(f) = r.file.as_mut() {
                    let _ = f.flush();
                }
                r.flushed = Instant::now();
            }
        }
        self.inner.output(bytes);
    }

    fn state(&self, state: &str, message: Option<String>) {
        {
            let mut r = self.rec.lock().unwrap();
            let prev = r.log.status.clone();
            match state {
                "connected" => {
                    if r.log.connected_at == 0 {
                        r.log.connected_at = now_ms();
                    } else if prev == "reconnecting" {
                        r.log.reconnects += 1;
                    }
                    r.log.message.clear();
                }
                "ended" | "failed" => {
                    r.log.ended_at = now_ms();
                    if let Some(f) = r.file.as_mut() {
                        let _ = f.flush();
                    }
                }
                _ => {}
            }
            // a failed connect keeps the session waiting for a manual retry; a later close is still a failure
            if !(prev == "failed" && state == "ended") {
                r.log.status = state.to_string();
            }
            if let Some(m) = &message {
                r.log.message = m.clone();
            }
            if state == "connecting" || state == "reconnecting" {
                r.log.ended_at = 0;
            }
            let _ = self.store.log_upsert(&r.log);
        }
        self.inner.state(state, message);
    }

    fn progress(&self, line: &str) {
        {
            let mut r = self.rec.lock().unwrap();
            if r.log.events.len() < MAX_EVENTS {
                r.log.events.push(LogEvent { at: now_ms(), text: line.to_string() });
            }
            // saved with the next state change; failures are always followed by one
        }
        self.inner.progress(line);
    }
}

impl Drop for LoggingSink {
    fn drop(&mut self) {
        let r = self.rec.get_mut().unwrap();
        if let Some(f) = r.file.as_mut() {
            let _ = f.flush();
        }
        if r.log.ended_at == 0 {
            r.log.ended_at = now_ms();
            if !matches!(r.log.status.as_str(), "failed" | "ended") {
                r.log.status = "ended".into();
            }
            let _ = self.store.log_upsert(&r.log);
        }
    }
}

/// Read a transcript; very large ones are cut to their last `max` bytes.
pub fn read_transcript(path: &Path, max: u64) -> std::io::Result<Vec<u8>> {
    use std::io::{Read, Seek, SeekFrom};
    let mut f = File::open(path)?;
    let len = f.metadata()?.len();
    if len > max {
        f.seek(SeekFrom::Start(len - max))?;
    }
    let mut buf = Vec::with_capacity(len.min(max) as usize);
    f.read_to_end(&mut buf)?;
    Ok(buf)
}

/// Terminal output -> plain text: drops escape sequences and carriage returns, keeps UTF-8.
pub fn strip_ansi(b: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(b.len());
    let mut i = 0;
    while i < b.len() {
        match b[i] {
            0x1b => {
                i += 1;
                match b.get(i) {
                    // CSI: params/intermediates then one final byte 0x40..=0x7e
                    Some(b'[') => {
                        i += 1;
                        while i < b.len() && !(0x40..=0x7e).contains(&b[i]) {
                            i += 1;
                        }
                        i += 1;
                    }
                    // OSC / DCS / etc: until BEL or ESC \
                    Some(b']') | Some(b'P') | Some(b'_') | Some(b'^') | Some(b'X') => {
                        i += 1;
                        while i < b.len() && b[i] != 0x07 && !(b[i] == 0x1b && b.get(i + 1) == Some(&b'\\')) {
                            i += 1;
                        }
                        i += if b.get(i) == Some(&0x07) { 1 } else { 2 };
                    }
                    // charset selection etc: ESC + one or two bytes
                    Some(b'(') | Some(b')') | Some(b'#') => i += 2,
                    Some(_) => i += 1,
                    None => {}
                }
            }
            b'\r' => i += 1,
            0x08 => {
                out.pop();
                i += 1;
            }
            c if c < 0x20 && c != b'\n' && c != b'\t' => i += 1,
            c => {
                out.push(c);
                i += 1;
            }
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    struct Null;
    impl SessionSink for Null {
        fn output(&self, _: Vec<u8>) {}
        fn state(&self, _: &str, _: Option<String>) {}
    }

    #[test]
    fn records_lifecycle_and_transcript() {
        let dir = std::env::temp_dir().join(format!("termx-logs-{}", now_ms()));
        let store = Arc::new(Store::open(&dir).unwrap());
        let host = Host { id: "h1".into(), label: "web".into(), hostname: "10.0.0.1".into(), username: "root".into(), ..Default::default() };
        let sink = LoggingSink::new(Arc::new(Null), store.clone(), "tab/1", &host, true);
        sink.state("connecting", None);
        sink.progress("Resolving \"10.0.0.1\"");
        sink.state("connected", None);
        sink.output(b"hello\r\n".to_vec());
        sink.state("reconnecting", Some("lost".into()));
        sink.state("connected", None);
        sink.state("ended", None);
        let id = sink.rec.lock().unwrap().log.id.clone();
        drop(sink);
        let logs = store.logs_list(10).unwrap();
        assert_eq!(logs.len(), 1);
        let l = &logs[0];
        assert_eq!(l.status, "ended");
        assert_eq!(l.reconnects, 1);
        assert_eq!(l.bytes, 7);
        assert_eq!(l.events.len(), 1);
        assert_eq!(l.events[0].text, "Resolving \"10.0.0.1\"");
        assert!(l.transcript && l.connected_at > 0 && l.ended_at > 0);
        assert!(id.starts_with("tab1-"));
        let p = transcript_path(&store, &id).unwrap();
        assert_eq!(read_transcript(&p, 1024).unwrap(), b"hello\r\n");
        assert_eq!(read_transcript(&p, 3).unwrap(), b"o\r\n");
        let ids = store.logs_delete(None).unwrap();
        remove_transcripts(&store, &ids);
        assert!(!p.exists());
        assert!(transcript_path(&store, "../x").is_none());
        let _ = std::fs::remove_dir_all(dir);
    }

    #[test]
    fn strips_ansi() {
        let s = strip_ansi(b"\x1b]0;user@host\x07\x1b[1;32muser@host\x1b[0m:~$ ls\r\nab\x08c\x1b(B\n");
        assert_eq!(String::from_utf8(s).unwrap(), "user@host:~$ ls\nac\n");
    }

    #[test]
    fn failed_stays_failed() {
        let dir = std::env::temp_dir().join(format!("termx-logs2-{}", now_ms()));
        let store = Arc::new(Store::open(&dir).unwrap());
        let sink = LoggingSink::new(Arc::new(Null), store.clone(), "t2", &Host::default(), false);
        sink.state("failed", Some("Connection refused".into()));
        sink.state("ended", None);
        drop(sink);
        let l = &store.logs_list(1).unwrap()[0];
        assert_eq!((l.status.as_str(), l.message.as_str(), l.transcript), ("failed", "Connection refused", false));
        let _ = std::fs::remove_dir_all(dir);
    }
}
